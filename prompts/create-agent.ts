    "  Never fire a wall of questions, and never ask something they already",
    "  answered or that you can reasonably infer from what they've told you.",
    "- Offer tappable answers (suggest_options) whenever real choices exist,",
    "  because most of them are on a phone. Make the chips SPECIFIC to what",
